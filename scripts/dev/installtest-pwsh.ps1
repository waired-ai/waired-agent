function global:Stub-DetectPlatform { Write-Host '[itstub] detect-platform' }

# Service presence is a per-case fact since #660: the install-vs-update
# dispatch now asks whether the install is COMPLETE (binary AND registered
# service), so "a binary with no service" and "a real install" are two
# different hosts and the harness has to be able to express both.
#
# Off by default, because Stop-ExistingService / Stop-ServiceForUpdate branch
# on presence and would then reach Stop-Service and sc.exe, which are not
# stubbed. Only cases that return before any service work set it.
function global:Stub-GetService {
    param([string]$Name, $ErrorAction)
    if ($env:IT_SERVICE) { return [pscustomobject]@{ Name = $Name; Status = 'Running' } }
    return $null
}

function global:Stub-StartProcess {
    param([string]$FilePath, [string[]]$ArgumentList, [string]$Verb,
          [switch]$PassThru, [switch]$Wait, [switch]$NoNewWindow, $ErrorAction)
    $tag = if ($Verb) { "elevate verb=$Verb" } else { 'spawn' }
    Write-Host ("[itstub] {0} file={1} argc={2}" -f $tag, $FilePath, $ArgumentList.Count)
    # One line per token, NOT the joined string: whether a space-bearing path
    # survived as one argument is the whole of #177, and joining them back
    # together is exactly the mistake that made it invisible.
    for ($i = 0; $i -lt $ArgumentList.Count; $i++) {
        Write-Host ("[itstub] argv[{0}]={1}" -f $i, $ArgumentList[$i])
    }
    # The -Clean wipe is a real child (`powershell.exe ... -File uninstall.ps1
    # -Clean -Yes [-DryRun]`), so run it in-process, where it inherits these
    # same aliases. installtest-dash.sh asserts the wipe child's own log for the
    # same reason: "install.ps1 printed that it would wipe" is not the contract.
    if (-not $Verb) {
        $f = [Array]::IndexOf($ArgumentList, '-File')
        if ($f -ge 0 -and ($f + 1) -lt $ArgumentList.Count) {
            $child = $ArgumentList[$f + 1].Trim('"')
            # Everything after the script path is a switch in this argv; bind by
            # name so the child gets real parameters rather than positionals.
            $childArgs = @{}
            for ($i = $f + 2; $i -lt $ArgumentList.Count; $i++) {
                $childArgs[$ArgumentList[$i].Trim('"').TrimStart('-')] = $true
            }
            Write-Host ("[itstub] child {0}" -f $child)
            try { & $child @childArgs } catch { Write-Host "[itstub] child-error $_" }
            Write-Host '[itstub] child-exit'
        }
    }
    $rc = 0
    if ($Verb) {
        # Stand in for the artefacts the elevated child leaves behind. The
        # parent's entire diagnosis is now built from these two files (#314),
        # so a stub that skipped them would make every interesting branch
        # unreachable -- which is exactly what the hardcoded ExitCode 0 below
        # used to do to the failure path.
        $s = [Array]::IndexOf($ArgumentList, '-StateFile')
        if ($s -ge 0 -and ($s + 1) -lt $ArgumentList.Count) {
            $statePath = $ArgumentList[$s + 1].Trim('"')
            if ($env:IT_ELEVATE_PROGRESS) {
                Set-Content -LiteralPath "$statePath.progress" -Value ($env:IT_ELEVATE_PROGRESS -split ',')
            }
            if ($env:IT_ELEVATE_STATUS) {
                Set-Content -LiteralPath "$statePath.status" -Value $env:IT_ELEVATE_STATUS
            }
        }
        if ($env:IT_ELEVATE_THROW) {
            # Shape-accurate on purpose. The real cmdlet catches the
            # Win32Exception ShellExecute raised -- 1223 when the user answers
            # No to UAC -- and rethrows a BARE InvalidOperationException with
            # no InnerException, on Windows PowerShell 5.1 and pwsh 7 alike.
            # Reproducing that exactly is the point: install.ps1 code that
            # tries `catch [Win32Exception]` or walks InnerException for
            # NativeErrorCode must fail this case rather than quietly never
            # firing on a real host.
            throw (New-Object System.InvalidOperationException(
                'This command cannot be run due to the error: The operation was canceled by the user.'))
        }
        if ($env:IT_ELEVATE_EXIT) { $rc = [int]$env:IT_ELEVATE_EXIT }
    }
    # install.ps1 no longer passes -Wait for the RunAs arm: it drives the wait
    # itself so it can mirror the child's transcript. So the object has to
    # answer .Handle / .HasExited / .WaitForExit() too, not just .ExitCode.
    $obj = [pscustomobject]@{ ExitCode = $rc; Handle = [IntPtr]::Zero; HasExited = $true }
    $obj | Add-Member -MemberType ScriptMethod -Name WaitForExit -Value { } -PassThru
}

