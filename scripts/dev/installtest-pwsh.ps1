# `-Control <url>` and `-DryRun` in one table without quoting them twice.
$P = @{}
if ($env:IT_ARGS) {
    foreach ($prop in (ConvertFrom-Json $env:IT_ARGS).PSObject.Properties) {
        $P[$prop.Name] = $prop.Value
    }
}
