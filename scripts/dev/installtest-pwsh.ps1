#!/usr/bin/env pwsh
# installtest-pwsh.ps1 -- fast, hermetic, infra-free guard for the install.ps1
# layer. The Windows counterpart of installtest-dash.sh: it drives
# packaging/install/install.ps1 across every CLI/env dispatch path in -DryRun
# and asserts the exit status AND the output, on any host with pwsh.
#
# Why: install.ps1 is 2500 lines with no verification outside the Windows VM
# leg. #177 (an unquoted argv token killed every non-admin install before
# diagnostics were armed) and #192 (WAIRED_* knobs did not survive the UAC
# boundary) both shipped through that gap. The VM leg costs ~5 min per push and
# its runner is already Administrator, so it never crosses Invoke-SelfElevate at
# all -- the exact code path #177 lived in.
#
# Hermetic: install.ps1's un-DryRun-guarded probes of host state are the four
# below, and they are the whole stub surface. Everything privileged goes through
# Common-Run, which is a no-op under -DryRun.
#
#   Test-Admin         WindowsIdentity -- throws outright off Windows; also the
#                      knob that picks elevated-inline vs UAC-handoff
#   Detect-Platform    OSVersion.Version.Build is 0 off Windows, so the real one
#                      dies on the Windows-10-1809 floor
#   Get-Service        the cmdlet does not exist off Windows
#   Start-Process      -Verb RunAs (UAC) and the -Clean wipe child
#   Invoke-RestMethod  api.github.com -- the latest-release lookup
#   Invoke-WebRequest  belt and braces; no case should reach it
#
# They are replaced from OUT HERE, by global aliases, which take precedence over
# a script's own functions. install.ps1 is not modified and carries no test-only
# branch -- the same arrangement as installtest-dash.sh's PATH stubs (CLAUDE.md
# "Test discipline": put the seam below the behaviour under test).
#
# What this does NOT cover, and the Windows leg still owns:
#   * Windows PowerShell 5.1. This runs pwsh 7, deliberately stricter (it also
#     turns Set-StrictMode on, which production does not) -- the dash-vs-sh
#     trade: a stricter interpreter finds latent bugs, and 5.1-only behaviour
#     is what installtest (windows) is for.
#   * Anything past Common-Run: SCM, the registry, WScript.Shell, the real
#     download, a real UAC prompt.
#
# Usage:
#   pwsh -NoProfile -File scripts/dev/installtest-pwsh.ps1
#   $env:INSTALL_PS1 = '/path/to/install.ps1'; pwsh -NoProfile -File ...

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$Root = (& git -C $PSScriptRoot rev-parse --show-toplevel).Trim()
$InstallPs1 = if ($env:INSTALL_PS1) { $env:INSTALL_PS1 } else { Join-Path $Root 'packaging/install/install.ps1' }
if (-not (Test-Path -LiteralPath $InstallPs1)) {
    Write-Error "install.ps1 not found: $InstallPs1"
    exit 1
}

# --- host tree ---------------------------------------------------------
# A Windows-shaped filesystem the cases can install into. The directory name
# carries a space on purpose: %ProgramFiles% always has one, and that is the
# token #177 was about.
$Work = Join-Path ([IO.Path]::GetTempPath()) ("waired-installtest-pwsh-" + [Guid]::NewGuid().ToString('N'))
$Host_PF   = Join-Path $Work 'Program Files'
$Host_PD   = Join-Path $Work 'ProgramData'
$Host_TEMP = Join-Path $Work 'Temp Dir'
$Host_WIN  = Join-Path $Work 'Windows'
$Host_USER = Join-Path $Work 'Users/tester'
foreach ($d in @($Host_PF, $Host_PD, $Host_TEMP, (Join-Path $Host_WIN 'System32'), $Host_USER,
                 (Join-Path $Host_USER 'AppData/Roaming'), (Join-Path $Host_USER 'AppData/Local'))) {
    New-Item -ItemType Directory -Path $d -Force | Out-Null
}

# --- the stub preamble each case runs ----------------------------------
# Generated rather than shipped as a second file, so the stubs and the cases
# that depend on them stay in one place (installtest-dash.sh writes its PATH
# stubs the same way).
$Preamble = Join-Path $Work 'stubs.ps1'
Set-Content -LiteralPath $Preamble -Encoding utf8 -Value @'
# Generated by scripts/dev/installtest-pwsh.ps1. Runs install.ps1 with the host
# boundary replaced by global aliases -- which beat a script's own functions,
# so install.ps1 needs no seam of its own.
Set-StrictMode -Version Latest

